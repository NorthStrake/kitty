def _add_target_calendar_features(frame, target_dates, base_date):
    out = frame.copy()
    td = pd.to_datetime(target_dates)
    out['target_month_sin'] = np.sin(2 * np.pi * td.dt.month / 12)
    out['target_month_cos'] = np.cos(2 * np.pi * td.dt.month / 12)
    out['target_time_index'] = ((td.dt.year - base_date.year) * 12
                                + (td.dt.month - base_date.month))
    return out


def _make_model(cat_cols, num_cols):
    pre = ColumnTransformer(
        transformers=[
            ('categorical',
             Pipeline([('imputer', SimpleImputer(strategy='most_frequent')),
                       ('onehot', OneHotEncoder(handle_unknown='ignore'))]),
             cat_cols),
            ('numeric',
             Pipeline([('imputer', SimpleImputer(strategy='median'))]),
             num_cols),
        ],
        remainder='drop')
    return Pipeline([
        ('preprocessor', pre),
        ('xgb', XGBRegressor(
            n_estimators=350, max_depth=5, learning_rate=0.04, subsample=0.85,
            colsample_bytree=0.85, objective='reg:squarederror',
            random_state=RANDOM_STATE, n_jobs=-1)),
    ])


def train_models(freight_rates, market):
    # df_merged = df3.merge(df4, on='date', how='inner').set_index('date')
    df_merged = freight_rates.merge(market, on='date', how='inner').set_index('date')

    raw = df_merged.copy()
    raw.index = pd.to_datetime(raw.index, errors='coerce')
    raw = raw.loc[raw.index.notna()].copy()
    raw.index.name = 'date'
    raw = raw.reset_index()
    raw['date'] = pd.to_datetime(raw['date']).dt.to_period('M').dt.to_timestamp()
    raw = raw.drop(columns=['rate_id'], errors='ignore')
    raw[TARGET] = pd.to_numeric(raw[TARGET], errors='coerce')
    raw = raw.dropna(subset=[TARGET]).copy()

    for col in GROUP_COLS:
        if col not in raw.columns:
            raw[col] = 'Unknown'
        raw[col] = raw[col].fillna('Unknown').astype(str)

    numeric_cols = [c for c in raw.select_dtypes(include=[np.number]).columns
                    if c != TARGET]
    agg = {c: 'mean' for c in numeric_cols}
    agg[TARGET] = 'mean'

    monthly = (raw.groupby(['date'] + GROUP_COLS, as_index=False, dropna=False)
                  .agg(agg)
                  .sort_values(['route_id', 'origin_port_id',
                                'destination_port_id', 'vessel_type', 'date'])
                  .reset_index(drop=True))
    if monthly.empty:
        raise ValueError('No usable monthly records remain after preparation.')

    first_historical_date = monthly['date'].min()

    # Lag features, then rolling means (strictly past values)
    grouped = monthly.groupby(GROUP_COLS, sort=False, dropna=False)
    for lag in LAGS:
        monthly['rate_lag_%d' % lag] = grouped[TARGET].shift(lag)

    grouped = monthly.groupby(GROUP_COLS, sort=False, dropna=False)
    for w in WINDOWS:
        monthly['rate_rolling_mean_%d' % w] = grouped[TARGET].transform(
            lambda s, w=w: s.shift(1).rolling(w, min_periods=1).mean())

    # Future targets (1..4 observations ahead within the same series)
    for h in HORIZONS:
        monthly['target_h%d' % h] = (
            monthly.groupby(GROUP_COLS, sort=False, dropna=False)[TARGET].shift(-h))
        monthly['target_date_h%d' % h] = (
            monthly.groupby(GROUP_COLS, sort=False, dropna=False)['date'].shift(-h))

    base_date = first_historical_date

    lag_cols = (['rate_lag_%d' % l for l in LAGS]
                + ['rate_rolling_mean_%d' % w for w in WINDOWS])
    excluded = {'date', TARGET, 'rate_id',
                *['target_h%d' % h for h in HORIZONS],
                *['target_date_h%d' % h for h in HORIZONS]}
    base_features = list(dict.fromkeys(
        c for c in GROUP_COLS + numeric_cols + lag_cols
        if c in monthly.columns and c not in excluded))
    features = base_features + ['target_month_sin', 'target_month_cos',
                                'target_time_index']
    cat_cols = [c for c in GROUP_COLS if c in features]
    num_cols = [c for c in features if c not in cat_cols]

    models = {}
    for h in HORIZONS:
        tc, tdc = 'target_h%d' % h, 'target_date_h%d' % h
        frame = _add_target_calendar_features(
            monthly[['date'] + base_features + [tc, tdc]].copy(),
            monthly[tdc], base_date)
        frame = frame.dropna(subset=[tc, tdc]).copy()
        models[h] = _make_model(cat_cols, num_cols).fit(frame[features], frame[tc])

    return {'models': models, 'features': features, 'base_date': base_date}


def _file_signature(paths):
    sig = {}
    for p in paths:
        st = os.stat(p)
        sig[os.path.basename(p)] = (st.st_size, int(st.st_mtime))
    return sig


def load_or_train(freight_rates, market, rate_paths, force_retrain=False):
    sig = _file_signature(rate_paths)
    if not force_retrain and os.path.exists(MODEL_CACHE):
        try:
            bundle = joblib.load(MODEL_CACHE)
            if bundle.get('signature') == sig:
                return bundle
            print('Cached models are out of date (CSV changed) - retraining...')
        except Exception as exc:
            print('Could not read model cache (%s) - retraining...' % exc)
    print('Training freight-rate models (one-off, takes a minute)...')
    bundle = train_models(freight_rates, market)
    bundle['signature'] = sig
    try:
        joblib.dump(bundle, MODEL_CACHE)
    except OSError as exc:       # e.g. read-only folder: just carry on
        print('Note: could not save model cache (%s). Continuing without it.' % exc)
    return bundle


